"use client";

import { useState } from "react";
import { toast } from "sonner";
import { Anchor, FileDown, HeartPulse, Package, Play, Route, Ship, Droplets, Wrench } from "lucide-react";
import { Bar, BarChart, CartesianGrid, ErrorBar, ResponsiveContainer, Tooltip, XAxis, YAxis } from "recharts";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/components/ui/tabs";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/misc";
import { PageHeader, Stat, OpsMap, RangeBar, AiTag, Confidence } from "@/components/shared";
import { damageAreas, allocations, restoration, sites } from "@/lib/mock/scenario";
import { fmt } from "@/lib/utils";

export function RecoverView() {
  const [running, setRunning] = useState(false);
  const maxDisp = Math.max(...damageAreas.map((a) => a.displaced.high));
  const maxHouses = Math.max(...damageAreas.map((a) => a.housesDamaged.high));
  const tot = damageAreas.reduce(
    (a, d) => ({ hl: a.hl + d.housesDamaged.low, he: a.he + d.housesDamaged.expected, hh: a.hh + d.housesDamaged.high, roads: a.roads + d.roadsBlockedKm, towers: a.towers + d.towersDown }),
    { hl: 0, he: 0, hh: 0, roads: 0, towers: 0 }
  );
  const sum = (k: "boats" | "reliefPacks" | "medicalTeams" | "waterLitres") => allocations.reduce((a, x) => a + x[k], 0);
  const chart = damageAreas.map((a) => ({
    name: a.name,
    expected: a.displaced.expected,
    err: [a.displaced.expected - a.displaced.low, a.displaced.high - a.displaced.expected],
  }));

  const rerun = () => {
    setRunning(true);
    toast.info("Open Cat Model re-run queued", { description: "hazard.build → exposure.load → impact.calc → calibrate.xgb" });
    setTimeout(() => {
      setRunning(false);
      toast.success("Forecast v4 ready (demo)", { description: "No material change; Kalapara remains priority #1." });
    }, 1800);
  };

  return (
    <div className="flex flex-col gap-5 p-4 md:p-6">
      <PageHeader
        phase="Phase 3 · Recover"
        title="Damage forecast & response plan"
        subtitle="Open Cat Model (CLIMADA hazard × exposure × vulnerability, calibrated with XGBoost on past cyclones) forecasts damage by area with ranges. The Response Optimizer (OR-Tools) turns it into who goes where, with what."
        actions={
          <>
            <Button variant="outline" onClick={rerun} disabled={running}>
              <Play /> {running ? "Running…" : "Re-run forecast"}
            </Button>
            <Button onClick={() => toast.info("After-action report", { description: "Generated by the backend (PDF) once connected." })}>
              <FileDown /> After-action report
            </Button>
          </>
        }
      />

      <Alert>
        <AiTag>model</AiTag>
        <AlertTitle>Forecasts are scenarios, not certainties</AlertTitle>
        <AlertDescription>
          Area-level only (upazila / union). Ten-metre satellite imagery cannot see individual buildings. Calibration data for Bangladesh is still being validated — treat this as a preliminary model.
        </AlertDescription>
      </Alert>

      <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
        <Stat label="Houses damaged (expected)" value={fmt(tot.he)} hint={`range ${fmt(tot.hl)} – ${fmt(tot.hh)}`} tone="danger" />
        <Stat label="Roads blocked" value={`${tot.roads} km`} />
        <Stat label="Towers down (forecast)" value={tot.towers} />
        <Stat label="Boats allocated" value={sum("boats")} hint={`${fmt(sum("reliefPacks"))} relief packs · ${sum("medicalTeams")} medical teams`} />
      </div>

      <Tabs defaultValue="forecast">
        <TabsList>
          <TabsTrigger value="forecast">Damage forecast</TabsTrigger>
          <TabsTrigger value="response">Response plan</TabsTrigger>
          <TabsTrigger value="restore">Restoration order</TabsTrigger>
          <TabsTrigger value="model">Model card</TabsTrigger>
        </TabsList>

        <TabsContent value="forecast" className="flex flex-col gap-4">
          <Card className="py-2">
            <CardContent className="px-2">
              <Table>
                <TableHeader>
                  <TableRow>
                    <TableHead>#</TableHead>
                    <TableHead>Area</TableHead>
                    <TableHead className="w-[180px]">Displaced (low · exp · high)</TableHead>
                    <TableHead className="w-[160px]">Houses damaged</TableHead>
                    <TableHead>Confidence</TableHead>
                    <TableHead>Main drivers</TableHead>
                  </TableRow>
                </TableHeader>
                <TableBody>
                  {damageAreas.map((a) => (
                    <TableRow key={a.id}>
                      <TableCell className="font-bold">{a.priority}</TableCell>
                      <TableCell>
                        <div className="font-medium">{a.name}</div>
                        <div className="text-muted-foreground text-xs">{a.district} · pop. {fmt(a.population)}</div>
                      </TableCell>
                      <TableCell>
                        <RangeBar low={a.displaced.low} expected={a.displaced.expected} high={a.displaced.high} max={maxDisp} />
                        <div className="text-muted-foreground mt-1 text-[11px] tabular-nums">
                          {fmt(a.displaced.low)} · <b className="text-foreground">{fmt(a.displaced.expected)}</b> · {fmt(a.displaced.high)}
                        </div>
                      </TableCell>
                      <TableCell>
                        <RangeBar low={a.housesDamaged.low} expected={a.housesDamaged.expected} high={a.housesDamaged.high} max={maxHouses} />
                        <div className="text-muted-foreground mt-1 text-[11px] tabular-nums">exp. {fmt(a.housesDamaged.expected)}</div>
                      </TableCell>
                      <TableCell>
                        <Confidence value={a.confidence} />
                      </TableCell>
                      <TableCell className="min-w-[280px] text-xs whitespace-normal">{a.drivers.join(" · ")}</TableCell>
                    </TableRow>
                  ))}
                </TableBody>
              </Table>
            </CardContent>
          </Card>
          <div className="grid gap-4 lg:grid-cols-2">
            <Card>
              <CardHeader>
                <CardTitle>Displaced people by area</CardTitle>
                <CardDescription>Expected value with low–high range</CardDescription>
              </CardHeader>
              <CardContent className="h-[320px]">
                <ResponsiveContainer width="100%" height="100%">
                  <BarChart data={chart} margin={{ left: 4, right: 8, top: 8, bottom: 8 }}>
                    <CartesianGrid vertical={false} stroke="var(--border)" />
                    <XAxis dataKey="name" tick={{ fontSize: 11, fill: "var(--muted-foreground)" }} interval={0} angle={-25} textAnchor="end" height={50} />
                    <YAxis tick={{ fontSize: 11, fill: "var(--muted-foreground)" }} tickFormatter={(v) => `${Math.round(v / 1000)}k`} />
                    <Tooltip
                      formatter={(v) => fmt(Number(v))}
                      contentStyle={{ background: "var(--popover)", border: "1px solid var(--border)", borderRadius: 8, fontSize: 12 }}
                    />
                    <Bar dataKey="expected" fill="var(--chart-1)" radius={[4, 4, 0, 0]}>
                      <ErrorBar dataKey="err" width={6} stroke="var(--foreground)" strokeWidth={1.2} />
                    </Bar>
                  </BarChart>
                </ResponsiveContainer>
              </CardContent>
            </Card>
            <Card>
              <CardContent>
                <OpsMap layers={["damage", "track"]} className="h-[320px]" />
              </CardContent>
            </Card>
          </div>
        </TabsContent>

        <TabsContent value="response">
          <div className="grid gap-3 md:grid-cols-2 xl:grid-cols-3">
            {allocations.map((al) => {
              const a = damageAreas.find((d) => d.id === al.areaId)!;
              return (
                <Card key={al.areaId} className="gap-3">
                  <CardHeader>
                    <div className="flex items-center justify-between">
                      <CardTitle>
                        #{a.priority} {a.name}
                      </CardTitle>
                      <Badge variant={al.route === "open" ? "success" : al.route === "partial" ? "warning" : "danger"}>
                        <Route /> route {al.route}
                      </Badge>
                    </div>
                    <CardDescription>
                      {a.district} · first teams in ~{al.etaHours} h
                    </CardDescription>
                  </CardHeader>
                  <CardContent className="grid grid-cols-2 gap-2 text-sm">
                    <div className="flex items-center gap-2"><Ship className="text-muted-foreground size-4" /> {al.boats} boats</div>
                    <div className="flex items-center gap-2"><Package className="text-muted-foreground size-4" /> {fmt(al.reliefPacks)} packs</div>
                    <div className="flex items-center gap-2"><HeartPulse className="text-muted-foreground size-4" /> {al.medicalTeams} medical teams</div>
                    <div className="flex items-center gap-2"><Droplets className="text-muted-foreground size-4" /> {fmt(al.waterLitres)} L water</div>
                    <div className="bg-muted col-span-2 mt-1 rounded-md p-2 text-xs">
                      <AiTag>why</AiTag> <span className="ml-1">{al.reason}</span>
                    </div>
                  </CardContent>
                </Card>
              );
            })}
          </div>
        </TabsContent>

        <TabsContent value="restore">
          <Card className="py-2">
            <CardContent className="px-2">
              <Table>
                <TableHeader>
                  <TableRow>
                    <TableHead>Order</TableHead>
                    <TableHead>Asset</TableHead>
                    <TableHead>People restored</TableHead>
                    <TableHead>Crew</TableHead>
                    <TableHead>ETA</TableHead>
                    <TableHead>Dependency</TableHead>
                  </TableRow>
                </TableHeader>
                <TableBody>
                  {restoration.map((r) => {
                    const s = sites.find((x) => x.id === r.siteId)!;
                    return (
                      <TableRow key={r.siteId}>
                        <TableCell className="text-lg font-bold">{r.rank}</TableCell>
                        <TableCell>
                          <div className="flex items-center gap-2 font-medium">
                            {s.type === "port" ? <Anchor className="size-4" /> : <Wrench className="size-4" />} {s.name}
                          </div>
                          <div className="text-muted-foreground text-xs">{s.upazila}, {s.district}</div>
                        </TableCell>
                        <TableCell className="font-semibold tabular-nums">{fmt(r.populationRestored)}</TableCell>
                        <TableCell>{r.crew}</TableCell>
                        <TableCell>{r.etaHours} h</TableCell>
                        <TableCell className="text-muted-foreground text-xs">{r.dependency ?? "—"}</TableCell>
                      </TableRow>
                    );
                  })}
                </TableBody>
              </Table>
            </CardContent>
          </Card>
        </TabsContent>

        <TabsContent value="model" className="grid gap-4 lg:grid-cols-2">
          <Card>
            <CardHeader>
              <CardTitle>Open Cat Model v0.1 (preliminary)</CardTitle>
              <CardDescription>How the number is built</CardDescription>
            </CardHeader>
            <CardContent className="flex flex-col gap-2 text-sm">
              {[
                ["Hazard", "Track & wind (IBTrACS history, live forecast), surge, flood depth (GloFAS, Sentinel-1, verified ground points)"],
                ["Exposure", "Building footprints (Google Open Buildings, Microsoft, OSM), roads, towers, substations, population (WorldPop)"],
                ["Vulnerability", "Published damage curves per structure type, adjusted locally"],
                ["Calibration", "XGBoost residual model trained on past cyclones vs. official damage reports"],
                ["Update", "Re-runs on each satellite pass or batch of verified reports; range narrows"],
              ].map(([k, v]) => (
                <div key={k} className="grid grid-cols-[110px_1fr] gap-2 border-b pb-2 last:border-0">
                  <div className="font-medium">{k}</div>
                  <div className="text-muted-foreground">{v}</div>
                </div>
              ))}
            </CardContent>
          </Card>
          <Card>
            <CardHeader>
              <CardTitle>Backtest status</CardTitle>
              <CardDescription>Shown honestly, including where the model is weak</CardDescription>
            </CardHeader>
            <CardContent className="flex flex-col gap-3 text-sm">
              <Alert variant="warning">
                <AlertTitle>Not yet backtested</AlertTitle>
                <AlertDescription>
                  Backtest against past Bangladesh cyclones runs once historical damage records are loaded in the backend. Error metrics will appear here per area.
                </AlertDescription>
              </Alert>
              <div className="text-muted-foreground text-xs">
                Planned metrics: mean absolute error per upazila, share of official values inside the low–high range, and bias by distance from landfall.
              </div>
            </CardContent>
          </Card>
        </TabsContent>
      </Tabs>
    </div>
  );
}
